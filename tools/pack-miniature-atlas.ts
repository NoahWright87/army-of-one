/** Pack delivered PNGs without changing pixels; runtime aliases share one GPU source. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { PNG } from 'pngjs';
import { miniatureFiles } from '../src/content/miniatures';
const width = 1024,
  items: { key: string; x: number; y: number; w: number; h: number; p: PNG }[] = [];
let x = 2,
  y = 2,
  rowHeight = 0;
for (const spec of miniatureFiles()) {
  const p = PNG.sync.read(readFileSync(`assets/miniatures/${spec.file}`));
  if (x + p.width + 2 > width) {
    x = 2;
    y += rowHeight + 4;
    rowHeight = 0;
  }
  items.push({ key: spec.key, x, y, w: p.width, h: p.height, p });
  x += p.width + 4;
  rowHeight = Math.max(rowHeight, p.height);
}
const height = 2 ** Math.ceil(Math.log2(y + rowHeight + 2)),
  atlas = new PNG({ width, height });
for (const item of items) PNG.bitblt(item.p, atlas, 0, 0, item.w, item.h, item.x, item.y);
mkdirSync('assets/atlases', { recursive: true });
writeFileSync('assets/atlases/miniatures.png', PNG.sync.write(atlas));
const frames = Object.fromEntries(items.map(({ key, x, y, w, h }) => [key, { x, y, w, h }]));
writeFileSync(
  'src/content/miniature-atlas.ts',
  `/** Generated by tools/pack-miniature-atlas.ts. */\nexport const MINIATURE_ATLAS = ${JSON.stringify({ key: 'mini_atlas', width, height, frames }, null, 2)} as const;\n`,
);
