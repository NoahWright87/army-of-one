/** Builds `assets/ASSETS.md` (the human/agent-readable replacement list) from the manifest. */
import { ASSET_MANIFEST, type AssetEntry } from '../src/content/assets';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function sizeOf(a: AssetEntry): string {
  if (a.kind === 'image') return `${a.size.w}×${a.size.h}`;
  return `${a.durationMs} ms${a.loop ? ' (loop)' : ''}`;
}

export function buildAssetsMd(manifest: readonly AssetEntry[] = ASSET_MANIFEST): string {
  const pending = manifest.filter((a) => a.status === 'placeholder').length;
  const lines = [
    '# Assets',
    '',
    '<!-- GENERATED by `npm run gen:placeholders` from src/content/assets.ts. Do not edit. -->',
    '',
    `${manifest.length} assets, ${pending} still placeholder.`,
    '',
    'To replace one: put the real file under `assets/`, point its manifest entry `file` at it,',
    "set `status: 'final'`, and rerun `npm run gen:placeholders`. Code refers to assets by key",
    'only, so nothing else changes. Keep the size/framing in the brief (soldiers face +x, etc.).',
    '',
  ];
  for (const kind of ['image', 'sound'] as const) {
    lines.push(`## ${kind === 'image' ? 'Images' : 'Sounds'}`, '');
    lines.push('| Key | Status | Size | File | Represents | Replacement brief |');
    lines.push('|---|---|---|---|---|---|');
    for (const a of manifest.filter((m) => m.kind === kind)) {
      lines.push(
        `| \`${a.key}\` | ${a.status} | ${sizeOf(a)} | \`${a.file}\` | ${esc(a.represents)} | ${esc(a.replacementBrief)} |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}
